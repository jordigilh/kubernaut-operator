package main

import (
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

func TestCoverage(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Independent business coverage gate")
}

var _ = Describe("raw-block coverage enforcement", func() {
	It("UT-AUDIT-515-GATE-001: rejects a zero-execution block even when a rounded report could say 100.0%", func() {
		profile := "mode: atomic\nexample/internal/policy/a.go:3.1,4.2 9999 1\n" +
			"example/internal/policy/a.go:5.1,5.2 1 0\n"
		blocks, err := readProfile(strings.NewReader(profile))
		Expect(err).NotTo(HaveOccurred())
		report := summarize(blocks)
		Expect(report.Statements).To(Equal(uint64(10000)))
		Expect(report.Missed).To(Equal(uint64(1)))
	})

	It("UT-AUDIT-515-GATE-002: rejects malformed profiles rather than silently ignoring rows", func() {
		for _, text := range []string{
			"", "mode: fake\n", "mode: set\nmalformed\n",
			"mode: set\na.go:2.1,1.2 1 1\n", "mode: set\na.go:1.1,2.2 -1 1\n",
		} {
			_, err := readProfile(strings.NewReader(text))
			Expect(err).To(HaveOccurred())
		}
	})

	It("UT-AUDIT-515-GATE-003: unions duplicate blocks without double-counting statements", func() {
		blocks, err := readProfile(strings.NewReader("mode: set\na.go:1.1,2.2 2 0\na.go:1.1,2.2 2 1\n"))
		Expect(err).NotTo(HaveOccurred())
		report := summarize(blocks)
		Expect(report.Statements).To(Equal(uint64(2)))
		Expect(report.Missed).To(Equal(uint64(0)))
		Expect(uncoveredBlocks(blocks)).To(BeEmpty(), "the detailed report must agree with the union summary")
	})

	It("UT-AUDIT-515-GATE-004: inventories handwritten functions absent from the profile", func() {
		source := "package policy\nfunc classify() int { return 1 }\nfunc decide() int { return 2 }\n"
		functions, err := sourceFunctions(token.NewFileSet(), "internal/policy/a.go", []byte(source))
		Expect(err).NotTo(HaveOccurred())
		Expect(functions).To(HaveLen(2))
		Expect(functions[0].Name).To(Equal("classify"))
		Expect(functions[1].Name).To(Equal("decide"))
		blocks, err := readProfile(strings.NewReader("mode: atomic\ninternal/policy/a.go:2.21,2.33 1 1\n"))
		Expect(err).NotTo(HaveOccurred())
		Expect(missingFunctions(functions, blocks)).To(ContainElement(HaveField("Name", "decide")))
	})

	It("UT-AUDIT-515-GATE-005: rejects removed blocks and altered statement weights", func() {
		baseline, err := readProfile(strings.NewReader("mode: atomic\na.go:1.1,2.2 2 0\na.go:3.1,4.2 1 0\n"))
		Expect(err).NotTo(HaveOccurred())
		partial, err := readProfile(strings.NewReader("mode: atomic\na.go:1.1,2.2 2 1\n"))
		Expect(err).NotTo(HaveOccurred())
		Expect(validateSchema(partial, baseline)).To(MatchError(ContainSubstring("missing instrumentation block")))
		altered, err := readProfile(strings.NewReader("mode: atomic\na.go:1.1,2.2 1 1\na.go:3.1,4.2 1 1\n"))
		Expect(err).NotTo(HaveOccurred())
		Expect(validateSchema(altered, baseline)).To(MatchError(ContainSubstring("instrumentation differs")))
		Expect(validateSchema(baseline, baseline)).To(Succeed())
	})

	It("UT-AUDIT-515-GATE-006: includes handwritten initializer-only files and excludes generated files", func() {
		root, err := os.MkdirTemp("", "coverage-inventory-")
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { Expect(os.RemoveAll(root)).To(Succeed()) })
		for _, directory := range []string{"api", "cmd", "internal"} {
			Expect(os.Mkdir(filepath.Join(root, directory), 0o700)).To(Succeed())
		}
		Expect(os.WriteFile(filepath.Join(root, "internal", "initializer.go"), []byte(
			"package internal\nvar decision = func() int { return 1 }()\n"), 0o600)).To(Succeed())
		Expect(os.WriteFile(filepath.Join(root, "internal", "generated.go"), []byte(
			"// Code generated by fixture. DO NOT EDIT.\npackage internal\n"+
				"func Generated() int { return 1 }\n"), 0o600)).To(Succeed())
		functions, handwritten, err := inventory(root)
		Expect(err).NotTo(HaveOccurred())
		Expect(functions).To(BeEmpty())
		Expect(handwritten).To(HaveKey("internal/initializer.go"))
		Expect(handwritten).NotTo(HaveKey("internal/generated.go"))
		blocks, err := readProfile(strings.NewReader("mode: atomic\nexample/internal/initializer.go:2.27,2.39 1 0\n"))
		Expect(err).NotTo(HaveOccurred())
		Expect(summarize(scopedBlocks(blocks, functions, handwritten, "example")).Missed).To(Equal(uint64(1)))
	})

	It("UT-AUDIT-515-GATE-007: rejects inconsistent duplicate weights in either profile", func() {
		baseline, err := readProfile(strings.NewReader("mode: atomic\na.go:1.1,2.2 2 0\n"))
		Expect(err).NotTo(HaveOccurred())
		conflicting, err := readProfile(strings.NewReader("mode: atomic\na.go:1.1,2.2 3 0\na.go:1.1,2.2 2 1\n"))
		Expect(err).NotTo(HaveOccurred())
		Expect(validateSchema(baseline, conflicting)).To(HaveOccurred(),
			"last-row wins must not hide a malformed instrumentation baseline")
		Expect(validateSchema(conflicting, baseline)).To(HaveOccurred())
	})

	It("UT-AUDIT-515-GATE-008: emits deterministic uncovered-block diagnostics", func() {
		blocks, err := readProfile(strings.NewReader("mode: atomic\nb.go:3.1,4.2 1 0\na.go:2.1,2.2 1 0\na.go:1.1,1.2 1 0\n"))
		Expect(err).NotTo(HaveOccurred())
		for range 20 {
			Expect(uncoveredBlocks(blocks)).To(Equal([]coverageBlock{blocks[2], blocks[1], blocks[0]}))
		}
	})

	It("UT-AUDIT-515-PYRAMID-001: runs independent CI lanes and a controller-only integration floor", func() {
		makefile, err := os.ReadFile("../../Makefile")
		Expect(err).NotTo(HaveOccurred())
		Expect(string(makefile)).To(ContainSubstring("go tool cover -func=cover-integration-controller.out"))
		workflow, err := os.ReadFile("../../.github/workflows/test.yml")
		Expect(err).NotTo(HaveOccurred())
		Expect(string(workflow)).To(ContainSubstring("name: Run independent unit tests"))
		Expect(string(workflow)).To(ContainSubstring("name: Run independent integration tests"))
		Expect(string(workflow)).To(ContainSubstring("run: make test-integration"))
		Expect(string(workflow)).To(ContainSubstring("if: ${{ !cancelled() }}"))
	})

	It("UT-AUDIT-515-GATE-009: executes the verifier and rejects incomplete unit evidence", func() {
		root, err := os.MkdirTemp("", "coverage-execution-")
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { Expect(os.RemoveAll(root)).To(Succeed()) })
		for _, directory := range []string{"api", "cmd", "internal"} {
			Expect(os.Mkdir(filepath.Join(root, directory), 0o700)).To(Succeed())
		}
		sourcePath := filepath.Join(root, "internal", "policy.go")
		source := "package policy\nfunc decide() int {\n value := 1\n return value\n}\n"
		Expect(os.WriteFile(sourcePath, []byte(source), 0o600)).To(Succeed())
		baselinePath, profilePath := filepath.Join(root, "baseline.out"), filepath.Join(root, "unit.out")
		baseline := "mode: atomic\ninternal/policy.go:3.2,3.12 1 0\ninternal/policy.go:4.2,4.14 1 0\n"
		Expect(os.WriteFile(baselinePath, []byte(baseline), 0o600)).To(Succeed())
		runVerifier := func(profile string) (string, error) {
			Expect(os.WriteFile(profilePath, []byte(profile), 0o600)).To(Succeed())
			// Fixed command and generated local fixture paths, never remote input.
			command := exec.Command("go", "run", ".", "-root", root, "-baseline", baselinePath, profilePath) //nolint:gosec
			output, runErr := command.CombinedOutput()
			return string(output), runErr
		}
		covered := strings.ReplaceAll(baseline, "1 0", "1 1")
		output, err := runVerifier(covered)
		Expect(err).NotTo(HaveOccurred(), output)
		Expect(output).To(ContainSubstring("statements: 2; missed: 0; missing functions: 0"))
		output, err = runVerifier(baseline)
		Expect(err).To(HaveOccurred())
		Expect(output).To(ContainSubstring("statements: 2; missed: 2"))
		Expect(output).To(ContainSubstring("do not substitute integration coverage"))
		output, err = runVerifier("mode: atomic\n")
		Expect(err).To(HaveOccurred())
		Expect(output).To(ContainSubstring("coverage blocks missing"))
		output, err = runVerifier("mode: atomic\ninternal/policy.go:3.2,3.12 1 1\n")
		Expect(err).To(HaveOccurred())
		Expect(output).To(ContainSubstring("missing instrumentation block"))
		Expect(os.WriteFile(sourcePath, []byte(source+"func uninstrumented() int { return 2 }\n"), 0o600)).To(Succeed())
		output, err = runVerifier(covered)
		Expect(err).To(HaveOccurred())
		Expect(output).To(ContainSubstring("missing functions: 1"))
	})
})
